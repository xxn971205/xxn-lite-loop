export function describeAction({ kind, code, refs, full, fullReReview }) {
  const detail = kind === 'patrol-review' && (full || code === 'full') ? 'full'
    : kind === 'review-dispatch' && (fullReReview || code === 'full-review') ? 'full-review' : code;
  const keys = [`${kind}:${detail}`, detail, kind];
  const key = keys.find((candidate) => Object.hasOwn(ACTION_MESSAGES, candidate));
  if (!key) return '请查看巡检记录';
  const count = refs?.length;
  return ACTION_MESSAGES[key].replace('{n}', count || '几');
}

export function formatScriptComment(slot, code, text) {
  const prefix = /^【[^】\r\n]+】/.exec(text)?.[0] ?? '';
  const summary = describeAction({ kind: 'comment-posted', code });
  const detail = text.slice(prefix.length);
  return `巡检脚本 ｜ ${slot} ｜ ${code}\n${prefix}${summary}。${detail && detail !== summary + '。' ? `\n${detail}` : ''}`;
}
